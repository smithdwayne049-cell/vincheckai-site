def install(root):
    keys = COPY['en']
    for lang, values in COPY.items():
        assert len(values) == len(keys), lang
        path = root/'i18n'/f'{lang}.json'
        strings = json.loads(path.read_text(encoding='utf-8'))
        for key, value in zip(keys, values):
            for brand in BRANDS if '{brand}' in key else ('',):
                strings[key.format(brand=brand)] = value.format(brand=brand)
        path.write_text(json.dumps(strings, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')

